DISTORTION = (0.0, 0.1)
# 网格弯曲度：板是刚体，必须为 0，否则切出来的格子不是平面四边形的透视投影
NORMALIZE = (0.0, 0.0)
# 数字四边形面积（像素²）：≈ 45×45 ~ 280×280，<1 时按占平坦区域面积的比例解释
# 切几块、每块多大全由它决定：从该区间采样目标面积，平坦区域总面积 / 目标面积 = 格子数
# 板面会按 BOARD_MARGIN 自动放大 (1-2*BOARD_MARGIN)^-2 ≈ 2.44 倍，给数字留出板边
AREA_RANGE = (10000, 80000)
# 笔画粗细 / 画布尺寸的候选，用来增加字形多样性
THICKNESS_CHOICES = (-1, 0, 0, 1, 1, 2, 3,)
CANVAS_CHOICES = (48, 64, 64, 80)
# 每个数字渲染几个字形变体（不同字体 / 字重 / 画布）
FONT_VARIANTS = 3


# 从候选板位里选多少块真放数字（仅当 SAMPLE_DIGIT_RANGE 为 None 时作为旧逻辑使用）
QUADS_SELECT_RATE = 0.5


# --------FUSE / DEFOCUS（数字融合 + 景深失焦）---------
# 数字与环境的对比度区间（|数字 - 背景| / 255），越大数字越醒目
CONTRAST_RANGE = (0.35, 0.70)
# 数字与环境的融合透明度区间，越大数字越「实」
FUSE_ALPHA = (0.55, 0.95)
# 失焦强度倍率：0 = 全部清晰，越大非基准平面的数字越糊
DEFOCUS_STRENGTH = .3
# 单块数字贴图的最大高斯 sigma（像素），同时是失焦封顶值
DEFOCUS_MAX_SIGMA = 4.0
# 同一块数字内部「近端 → 远端」的失焦差异比例（0 = 均匀失焦，0.5 = 远端 1.5 倍）
DEFOCUS_PERSPECTIVE = 0.5
# 失焦尺寸封顶：sigma <= DEFOCUS_SIZE_RATIO * 数字短边，保证远处小数字仍可辨认
DEFOCUS_SIZE_RATIO = 0.06


